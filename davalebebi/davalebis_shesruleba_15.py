# ============================================================
# Student კლასი
# ============================================================

class Student:

    # ========================================================
    # კონსტრუქტორი
    # ========================================================

    def __init__(self, name, age, course):

        # სტუდენტის სახელი
        self.name = name

        # სტუდენტის ასაკი
        self.age = age

        # სტუდენტის კურსი
        self.course = course


    # ========================================================
    # სტუდენტის ინფორმაციის ჩვენება
    # ========================================================

    def show_info(self):

        print("სახელი:", self.name)
        print("ასაკი:", self.age)
        print("კურსი:", self.course)
        print("საგანი: OOP")


# ============================================================
# Book კლასი
# ============================================================

class Book:

    # ========================================================
    # კონსტრუქტორი
    # ========================================================

    def __init__(self, title, author, year, genre):

        # წიგნის დასახელება
        self.title = title

        # წიგნის ავტორი
        self.author = author

        # წიგნის გამოცემის წელი
        self.year = year

        # წიგნის ჟანრი
        self.genre = genre


    # ========================================================
    # წიგნის ინფორმაციის ჩვენება
    # ========================================================

    def show_info(self):

        print("დასახელება:", self.title)
        print("ავტორი:", self.author)
        print("გამოცემის წელი:", self.year)
        print("ჟანრი:", self.genre)


    # ========================================================
    # ობიექტის ტექსტური სახით წარმოდგენა
    # ========================================================

    def __str__(self):

        return (
            f"წიგნი: {self.title}, "
            f"ავტორი: {self.author}, "
            f"წელი: {self.year}, "
            f"ჟანრი: {self.genre}"
        )


