# სტუდენტების მონაცემების შეყვანა
# ============================================================

# ციკლი შესრულდება იმდენჯერ,
# რამდენი სტუდენტიც მიუთითა მომხმარებელმა

for i in range(student_count):


    print()
    print("======================================")
    print(f"სტუდენტი №{i + 1}")
    print("======================================")


    # ========================================================
    # სტუდენტის სახელი
    # ========================================================

    while True:

        name = input(
            "შეიყვანეთ სტუდენტის სახელი: "
        ).strip().title()


        # სახელი არ უნდა იყოს ცარიელი

        if name == "":

            print(
                "შეცდომა! სახელი ცარიელი არ უნდა იყოს."
            )


        # სახელი არ უნდა შეიცავდეს ციფრებს

        elif any(
            character.isdigit()
            for character in name
        ):

            print(
                "შეცდომა! სახელი არ უნდა შეიცავდეს ციფრებს."
            )


        else:

            break


    # ========================================================
    # სტუდენტის ასაკი
    # ========================================================

    while True:

        try:

            age = int(
                input(
                    "შეიყვანეთ სტუდენტის ასაკი: "
                )
            )


            if age <= 0:

                raise ValueError(
                    "ასაკი უნდა იყოს 0-ზე მეტი."
                )


            break


        except ValueError as error:

            print(
                "შეცდომა:",
                error
            )


    # ========================================================
    # სტუდენტის კურსი
    # ========================================================

    while True:

        course = input(
            "შეიყვანეთ სტუდენტის კურსი: "
        ).strip()


        if course == "":

            print(
                "შეცდომა! კურსი ცარიელი არ უნდა იყოს."
            )


        else:

            break


    # ========================================================
    # Student ობიექტის შექმნა
    # ========================================================

    student = Student(
        name,
        age,
        course
    )


    # ========================================================
    # შექმნილი ობიექტის students სიაში დამატება
    # ========================================================

    students.append(student)


# ============================================================
# ყველა სტუდენტის ინფორმაციის ჩვენება
# ============================================================

print()
print("======================================")
print("ყველა სტუდენტის ინფორმაცია")
print("======================================")


# students სიაში უკვე Student ობიექტებია

for student in students:

    print()

    student.show_info()

    print("------------------------------")


