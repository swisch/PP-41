import csv


# ============================================================
# დავალება 1
# ორი მთელი რიცხვის შეყვანა და გაყოფა
# ============================================================

while True:

    try:

        num1 = int(
            input("შეიყვანეთ პირველი მთელი რიცხვი: ")
        )

        num2 = int(
            input("შეიყვანეთ მეორე მთელი რიცხვი: ")
        )

        # ვამოწმებთ, რომ მეორე რიცხვი არ იყოს 0
        if num2 == 0:
            raise ZeroDivisionError(
                "0-ზე გაყოფა არ შეიძლება"
            )

        result = num1 / num2

        print()
        print("გაყოფის შედეგია:", result)

        break


    except ValueError:

        print()
        print(
            "შეცდომა! შეიყვანეთ მხოლოდ მთელი რიცხვები."
        )


    except ZeroDivisionError as error:

        print()
        print("შეცდომა:", error)


# ============================================================
# დავალება 2
# ტექსტურ ფაილში სიტყვების, ხაზების
# და სიმბოლოების რაოდენობის დათვლა
# ============================================================

print()
print("======================================")
print("ფაილის ანალიზი")
print("======================================")
print()


try:

    # ვხსნით text.txt ფაილს წასაკითხად
    with open(
        "text.txt",
        "r",
        encoding="utf-8"
    ) as file:

        # მთლიან ფაილს ვინახავთ text ცვლადში
        text = file.read()


    # ========================================================
    # სიმბოლოების რაოდენობა
    # ========================================================

    characters_count = len(text)


    # ========================================================
    # სიტყვების რაოდენობა
    # ========================================================

    words = text.split()

    words_count = len(words)


    # ========================================================
    # ხაზების რაოდენობა
    # ========================================================

    lines = text.splitlines()

    lines_count = len(lines)


    print(
        "სიტყვების რაოდენობა:",
        words_count
    )

    print(
        "ხაზების რაოდენობა:",
        lines_count
    )

    print(
        "სიმბოლოების რაოდენობა:",
        characters_count
    )


except FileNotFoundError:

    print(
        "შეცდომა! text.txt ფაილი ვერ მოიძებნა."
    )


# ============================================================
# დავალება 3
# CSV ფაილში ინფორმაციის ჩაწერა
# ============================================================

print()
print("======================================")
print("CSV ფაილში ინფორმაციის ჩაწერა")
print("======================================")
print()


students = []


# ============================================================
# რამდენი სტუდენტის შეყვანა გვინდა
# ============================================================

while True:

    try:

        student_count = int(
            input(
                "შეიყვანეთ სტუდენტების რაოდენობა: "
            )
        )

        if student_count <= 0:

            raise ValueError(
                "სტუდენტების რაოდენობა უნდა იყოს 0-ზე მეტი"
            )

        break


    except ValueError as error:

        print()
        print("შეცდომა:", error)


# ============================================================
# სტუდენტების მონაცემების შეყვანა
# ============================================================

for i in range(student_count):

    print()
    print("სტუდენტი №", i + 1)


    # ========================================================
    # სახელი
    # ========================================================

    while True:

        name = input(
            "შეიყვანეთ სტუდენტის სახელი: "
        ).strip().title()

        if name == "":

            print(
                "შეცდომა! სახელი ცარიელი არ უნდა იყოს."
            )

        elif any(
            character.isdigit()
            for character in name
        ):

            print(
                "შეცდომა! სახელი არ უნდა შეიცავდეს ციფრებს."
            )

        else:

            break


    # ========================================================
    # ასაკი
    # ========================================================

    while True:

        try:

            age = int(
                input(
                    "შეიყვანეთ სტუდენტის ასაკი: "
                )
            )

            if age <= 0:

                raise ValueError(
                    "ასაკი უნდა იყოს 0-ზე მეტი"
                )

            break


        except ValueError as error:

            print()
            print("შეცდომა:", error)


    # ========================================================
    # ქულა
    # ========================================================

    while True:

        try:

            score = int(
                input(
                    "შეიყვანეთ სტუდენტის ქულა: "
                )
            )

            if score < 0 or score > 100:

                raise ValueError(
                    "ქულა უნდა იყოს 0-დან 100-მდე"
                )

            break


        except ValueError as error:

            print()
            print("შეცდომა:", error)


    # სტუდენტის ინფორმაციას ვამატებთ სიაში
    students.append(
        [name, age, score]
    )


# ============================================================
# CSV ფაილში ჩაწერა
# ============================================================

try:

    with open(
        "students.csv",
        "w",
        newline="",
        encoding="utf-8"
    ) as file:

        writer = csv.writer(file)


        # CSV ფაილის სათაურები
        writer.writerow(
            [
                "Name",
                "Age",
                "Score"
            ]
        )


        # სტუდენტების მონაცემების ჩაწერა
        for student in students:

            writer.writerow(student)


    print()
    print(
        "მონაცემები წარმატებით ჩაიწერა students.csv ფაილში."
    )


except Exception as error:

    print()
    print(
        "ფაილში ჩაწერის შეცდომა:",
        error
    )


# ============================================================
# CSV ფაილიდან ინფორმაციის წაკითხვა
# ============================================================

print()
print("======================================")
print("CSV ფაილის წაკითხვა")
print("======================================")
print()


try:

    with open(
        "students.csv",
        "r",
        encoding="utf-8"
    ) as file:

        reader = csv.reader(file)


        # CSV ფაილის თითოეული ხაზის წაკითხვა
        for row in reader:

            print(row)


except FileNotFoundError:

    print(
        "შეცდომა! students.csv ფაილი ვერ მოიძებნა."
    )