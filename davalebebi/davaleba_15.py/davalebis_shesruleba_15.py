def divide_numbers():

    try:

        # მომხმარებლისგან ორი მთელი რიცხვის მიღება
        number_1 = int(input("შეიყვანეთ პირველი მთელი რიცხვი: "))

        number_2 = int(input("შეიყვანეთ მეორე მთელი რიცხვი: "))


        # ----------------------------------------------------
        # ორ რიცხვს ვინახავთ numbers.txt ფაილში
        # ----------------------------------------------------

        with open("numbers.txt", "w", encoding="utf-8") as file:

            file.write(str(number_1) + "\n")
            file.write(str(number_2) + "\n")


        print()
        print("რიცხვები წარმატებით ჩაიწერა numbers.txt ფაილში.")


        # ----------------------------------------------------
        # ვკითხულობთ numbers.txt ფაილიდან მონაცემებს
        # ----------------------------------------------------

        with open("numbers.txt", "r", encoding="utf-8") as file:

            numbers = file.readlines()


        first_number = int(numbers[0])
        second_number = int(numbers[1])


        # ----------------------------------------------------
        # გაყოფა
        # ----------------------------------------------------

        result = first_number / second_number


        # ----------------------------------------------------
        # შედეგს ვინახავთ result.txt ფაილში
        # ----------------------------------------------------

        with open("result.txt", "w", encoding="utf-8") as file:

            file.write(f"{first_number} / {second_number} = {result}")


        print("გაყოფის შედეგი ჩაიწერა result.txt ფაილში.")
        print("შედეგი:", result)


    except ValueError:

        print()
        print("შეცდომა!")
        print("გთხოვთ შეიყვანოთ მხოლოდ მთელი რიცხვები.")


    except ZeroDivisionError:

        print()
        print("შეცდომა!")
        print("ნულზე გაყოფა შეუძლებელია.")


    except FileNotFoundError:

        print()
        print("შეცდომა!")
        print("ფაილი ვერ მოიძებნა.")



