def reverse_file_lines():

    try:

        file_name = input("შეიყვანეთ ფაილის სახელი: ")


        # ----------------------------------------------------
        # r+ ნიშნავს:
        # ფაილის წაკითხვაც შეგვიძლია
        # და ჩაწერაც
        # ----------------------------------------------------
        with open(file_name,"r+",encoding="utf-8") as file:


            # ყველა ხაზის წაკითხვა
            lines = file.readlines()
            reversed_lines = []

            # ------------------------------------------------
            # თითოეული ხაზის შებრუნება
            # ------------------------------------------------

            for line in lines:

                # \n-ს ვაშორებთ
                line = line.rstrip("\n")


                # [::-1] აბრუნებს სტრინგს
                reversed_line = line[::-1]

                # ახალ სიაში ვამატებთ
                reversed_lines.append(
                    reversed_line + "\n"
                )


            # ------------------------------------------------
            # ფაილის დასაწყისში დაბრუნება
            # ------------------------------------------------

            file.seek(0)


            # ------------------------------------------------
            # შებრუნებული ხაზების ჩაწერა
            # ------------------------------------------------

            file.writelines(reversed_lines)


            # ------------------------------------------------
            # ძველი ზედმეტი ინფორმაციის წაშლა
            # ------------------------------------------------

            file.truncate()


        print()
        print("ფაილის ხაზები წარმატებით შებრუნდა.")


    except FileNotFoundError:

        print()
        print("შეცდომა!")
        print("მითითებული ფაილი ვერ მოიძებნა.")



