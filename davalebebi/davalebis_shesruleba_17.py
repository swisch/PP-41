class Book: # მეორე კლასის სტრუქტურა წიგნის კლასისთვის და მაგისი მოქმედება 

    # ========================================================
    # კონსტრუქტორი
    # ========================================================

    def __init__(self, title, author, year, price):

        # წიგნის დასახელება
        self.title = title

        # ავტორი
        self.author = author

        # გამოცემის წელი
        self.year = year

        # წიგნის ფასი
        self.price = price


    # ========================================================
    # წიგნის ინფორმაციის ჩვენება
    # ========================================================

    def show_info(self):

        print()
        print("======================================")
        print("წიგნის ინფორმაცია")
        print("======================================")

        print("დასახელება:", self.title)

        print("ავტორი:", self.author)

        print("გამოცემის წელი:", self.year)

        print("ფასი:", self.price)


    # ========================================================
    # ფასის შეცვლა
    # ========================================================

    def change_price(self, new_price):

        if new_price <= 0:

            print(
                "შეცდომა! ფასი უნდა იყოს 0-ზე მეტი."
            )

        else:

            self.price = new_price

            print(
                "წიგნის ფასი წარმატებით შეიცვალა."
            )


