class Student: # პირველის სტრუქტურა სტუდენტის კლასისთვის და მერე მაგისი მოქმედება რომ წიგნის და სტუდენტი ერთმანეთში სტრუქტურაში არ აურიოთ.

    # ========================================================
    # კონსტრუქტორი
    # ========================================================
    # ეს კონსტრუქტორი გამოიყენება ობიექტის შექმნისას, რათა ავტომატურად დააყენოს ობიექტის თვისებები (attributes) და მიიღოს პარამეტრები.
    def __init__(self, name, surname, age, grades): # ობიექტის შექმნისას კონსტრუქტორი ავტომატურად იძახება და პარამეტრები გადაეცემა ობიექტის შექმნისას.
        #__init__ არის სპეციალური მეთოდი, რომელიც ავტომატურად იძახება ობიექტის შექმნის დროს.
        # როდესაც Python ხედავს: Student(...) ის ავტომატურად იძახებს: __init__() და მონაცემები ნაწილდება surname, age, grades
        # სტუდენტის სახელი # 
        self.name = name # self ნიშნავს კონკრეტულ ობიექტს, რომელთანაც ამ მომენტში ვმუშაობთ. student1 ... student3 ...
                         # self.name ნიშნავს, რომ ჩვენ ვქმნით ობიექტის თვისებას სახელად name და ვაკავშირებთ მას პარამეტრს name, რომელიც გადაეცემა კონსტრუქტორს ობიექტის შექმნისას.
        # სტუდენტის გვარი
        self.surname = surname

        # სტუდენტის ასაკი
        self.age = age

        # სტუდენტის შეფასებების სია
        self.grades = grades


    # ========================================================
    # სტუდენტის საშუალო ქულის დათვლა
    # ========================================================

    def calculate_average(self): # ეს მეთოდი ითვლის სტუდენტის შეფასებების საშუალო ქულას. self.grades არის სტუდენტის შეფასებების სია, რომელიც გადაეცემა ობიექტის შექმნისას.

        # თუ შეფასებების სია ცარიელია
        if len(self.grades) == 0:

            return 0


        total = 0


        # შევაჯამოთ ყველა შეფასება
        for grade in self.grades:

            total = total + grade


        average = total / len(self.grades)


        return average


    # ========================================================
    # სტუდენტის ინფორმაციის ჩვენება
    # ========================================================

    def show_info(self): # ეს მეთოდი აჩვენებს სტუდენტის ინფორმაციას, მათ შორის სახელს, გვარს, ასაკს, შეფასებებს და საშუალო ქულას.

        print()
        print("======================================")
        print("სტუდენტის ინფორმაცია")
        print("======================================")

        print("სახელი:", self.name)

        print("გვარი:", self.surname)

        print("ასაკი:", self.age)

        print("შეფასებები:", self.grades)

        print(
            "საშუალო ქულა:",
            self.calculate_average()
        )


